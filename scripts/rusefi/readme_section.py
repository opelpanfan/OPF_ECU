#!/usr/bin/env python3
"""Maintain the rusEFI section of a board branch's top-level readme.md.

Only the text between <!-- RUSEFI:START --> and <!-- RUSEFI:END --> is ever changed; if the
markers are missing the block is appended at the end. Other sections (FOME:START/END,
SPEEDUINO:START/END, the board description) are left byte-for-byte intact.

  readme_section.py update README RUSEFI_DIR BUILD_INFO   # rewrite the section in place
  readme_section.py check OLD NEW                           # exit 1 if text outside the markers differs
"""
import os
import sys

START = "<!-- RUSEFI:START -->"
END = "<!-- RUSEFI:END -->"

DESCR = {
    "rusefi_firmware.bin": "firmware image (flash at 0x08000000, e.g. DFU / ST-Link)",
    "rusefi_firmware.hex": "firmware, Intel HEX",
    "rusefi_firmware.srec": "firmware with CRC, S-record (OpenBLT / BootCommander)",
    "rusefi_firmware.dfu": "firmware, DfuSe file (rusEFI console / DfuSe tools)",
    "rusefi_tunerstudio.ini": "TunerStudio project .ini matching this firmware's signature",
    "rusefi_base_tune.msq": "base tune: board default configuration (rusEFI simulator canned-tune process)",
    "rusefi_console.zip": "rusEFI console: launchers from misc/console_launcher + console/rusefi_console.jar (Java 17+)",
    "rusefi_build_info.txt": "build metadata (rusEFI ref/commit, toolchain, signature)",
    "SHA256SUMS": "SHA-256 checksums of the files above",
}
ORDER = list(DESCR)


def split(text):
    """-> (before, after) outside the markers, or None if markers are absent/broken."""
    s = text.find(START)
    if s < 0:
        return None
    e = text.find(END, s)
    if e < 0:
        return None
    return text[:s], text[e + len(END):]


def outside(text):
    parts = split(text)
    return parts if parts is not None else (text, "")


def render(rusefi_dir, info):
    ref = info.get("rusefi_ref", "?")
    sha = info.get("rusefi_commit", "")
    files = sorted((f for f in os.listdir(rusefi_dir) if os.path.isfile(os.path.join(rusefi_dir, f))),
                   key=lambda f: (ORDER.index(f) if f in ORDER else len(ORDER), f))
    rel = f"https://github.com/rusefi/rusefi/releases/tag/{ref}"
    lines = [
        START,
        "## rusEFI firmware",
        "",
        f"- rusEFI version: [`{ref}`]({rel})"
        + (f" (commit [`{sha[:10]}`](https://github.com/rusefi/rusefi/commit/{sha}))" if sha else ""),
        f"- Build date: {info.get('built_utc', '?')}",
        f"- TunerStudio signature: `{info.get('ts_signature', '?')}`",
        "",
        "| File | Description |",
        "|---|---|",
    ]
    for f in files:
        lines.append(f"| [{f}](rusefi/{f}) | {DESCR.get(f, '')} |")
    lines += [
        "",
        "Console: [rusefi_console.zip](rusefi/rusefi_console.zip) is built here; upstream rusEFI releases no longer"
        f" ship a standalone console, only inside each board's `rusefi_bundle_*.zip` on the [release page]({rel}).",
        "",
        "_Generated by `scripts/rusefi/build_rusefi_core48.sh` (OPF_ECU `master-rusefi-grok`)._",
        END,
    ]
    return "\n".join(lines)


def update(readme, rusefi_dir, info_file):
    info = {}
    with open(info_file, encoding="utf-8") as f:
        for line in f:
            if "=" in line:
                k, v = line.rstrip("\n").split("=", 1)
                info[k] = v
    old = open(readme, encoding="utf-8", newline="").read() if os.path.exists(readme) else ""
    nl = "\r\n" if "\r\n" in old else "\n"   # keep the file's line endings (core48_21 readme is CRLF)
    block = render(rusefi_dir, info).replace("\n", nl)
    parts = split(old)
    if parts is None:
        sep = "" if old == "" else (nl if old.endswith("\n") else nl + nl)
        new = old + sep + block + nl
    else:
        new = parts[0] + block + parts[1]
    if outside(old) != outside(new) and parts is not None:
        sys.exit("internal error: text outside markers changed")
    if parts is None and not new.startswith(old):
        sys.exit("internal error: append altered existing text")
    with open(readme, "w", encoding="utf-8", newline="") as f:
        f.write(new)


def check(old_file, new_file):
    old = open(old_file, encoding="utf-8", newline="").read() if os.path.exists(old_file) else ""
    new = open(new_file, encoding="utf-8", newline="").read()
    if split(new) is None:
        sys.exit("readme.md: RUSEFI markers missing after update")
    if split(old) is None:
        p = split(new[len(old):]) if new.startswith(old) else None
        ok = p is not None and p[0].strip() == "" and p[1].strip() == ""
    else:
        ok = outside(old) == outside(new)
    if not ok:
        sys.exit("readme.md: text outside <!-- RUSEFI:START/END --> changed")
    print("readme.md: changes confined to the RUSEFI section")


if __name__ == "__main__":
    if len(sys.argv) == 5 and sys.argv[1] == "update":
        update(*sys.argv[2:])
    elif len(sys.argv) == 4 and sys.argv[1] == "check":
        check(*sys.argv[2:])
    else:
        sys.exit(__doc__)
