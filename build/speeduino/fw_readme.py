#!/usr/bin/env python3
"""Maintain the Speeduino section of a firmware branch readme (e.g. core48_21:readme.md).

Only the text between <!-- SPEEDUINO:START --> and <!-- SPEEDUINO:END --> is ever written; it is generated
from <firmware_dir>/build-info.json and never hand-edited. Everything else (FOME:START/END, RUSEFI:START/END
sections and all other text) is left byte-for-byte unchanged, line endings included.

  fw_readme.py update   README --dir DIR --branch BR --repo OWNER/REPO [--server URL] --release-tag TAG
  fw_readme.py check    OLD NEW       # exit 1 if anything outside the SPEEDUINO section differs
  fw_readme.py current  README --tag T  # exit 0 if README has an up-to-date generated section for tag T
  fw_readme.py render   ...same args as update...  # print the section only

If README has no markers yet, the existing Speeduino block (the "## Speeduino ..." heading up to the next
level-1/2 heading or other section marker, trailing blank lines excluded) is wrapped in the markers and its
content replaced; if there is no such block, the section is appended at the end of the file.
"""
import argparse, json, os, re, sys

START, END = "<!-- SPEEDUINO:START -->", "<!-- SPEEDUINO:END -->"
FMT = 2  # bump when the generated text changes so the workflow refreshes existing readmes
STAMP_RE = re.compile(r"<!-- generated by speeduino-autobuild: tag=(\S+) fmt=(\d+) ")
OTHER_MARKER = re.compile(r"^\s*<!--\s*[A-Z0-9_]+:(START|END)\s*-->\s*$")
LEGACY_HEAD = re.compile(r"^##\s+Speeduino\b", re.I)
ANY_HEAD = re.compile(r"^#{1,2}\s")

# The visible text is exactly the original hand-written block (core48_21 5c21224): heading, hint line and the
# two download badges (firmware .bin, TunerStudio ini). Only the markers and the invisible stamp comment are added.
BADGES = [
    ("speeduino_firmware.bin", "Firmware", "blue"),
    ("speeduino_tunerstudio.ini", "TunerStudio%20INI", "green"),
]
BADGE = ('[![Download zip](https://custom-icon-badges.demolab.com/badge/-Speeduino%%20%s-%s?style=for-the-badge'
         '&logo=download&logoColor=white "Download Speeduino %s")](%s)')


class Fail(Exception):
    pass


def read(path):
    with open(path, "rb") as f:
        return f.read().decode("utf-8")


def nl_of(text):
    return "\r\n" if "\r\n" in text else "\n"


def lines_of(text):
    return text.splitlines(keepends=True)


def find_section(lines):
    """(start, end) indexes of the marker lines, None if absent; Fail on malformed markers."""
    s = [i for i, l in enumerate(lines) if l.strip() == START]
    e = [i for i, l in enumerate(lines) if l.strip() == END]
    if not s and not e:
        return None
    if len(s) != 1 or len(e) != 1 or e[0] < s[0]:
        raise Fail("malformed SPEEDUINO markers (start at %s, end at %s)" % ([i + 1 for i in s], [i + 1 for i in e]))
    for i in range(s[0] + 1, e[0]):
        if OTHER_MARKER.match(lines[i]):
            raise Fail("another section marker inside the SPEEDUINO section (line %d): %s" % (i + 1, lines[i].strip()))
    return s[0], e[0]


def find_legacy(lines):
    """(start, end) inclusive line range of the pre-marker Speeduino block, None if absent."""
    heads = [i for i, l in enumerate(lines) if LEGACY_HEAD.match(l)]
    if not heads:
        return None
    if len(heads) > 1:
        raise Fail("more than one '## Speeduino' heading (lines %s) - add the SPEEDUINO markers by hand" % [i + 1 for i in heads])
    s = heads[0]
    e = len(lines)
    for i in range(s + 1, len(lines)):
        if ANY_HEAD.match(lines[i]) or OTHER_MARKER.match(lines[i]):
            e = i
            break
    e -= 1
    while e > s and not lines[e].strip():
        e -= 1
    return s, e


def strip_section(text, allow_legacy):
    """Text with our section removed (marker lines included)."""
    lines = lines_of(text)
    sec = find_section(lines)
    if sec is None and allow_legacy:
        sec = find_legacy(lines)
    if sec is not None:
        lines = lines[:sec[0]] + lines[sec[1] + 1:]
    # blank lines at the very end of the file are ignored (appending the section adds a separator there)
    return "".join(lines).rstrip("\r\n"), sec


def render(info, dirpath, branch, repo, server, release_tag, nl):
    d = os.path.basename(dirpath.rstrip("/"))
    raw = "https://raw.githubusercontent.com/%s/%s/%s/" % (repo, branch, d)
    missing = [f for f, _, _ in BADGES if not os.path.isfile(os.path.join(dirpath, f))]
    if missing:
        raise Fail("files linked from the section are missing in %s: %s" % (dirpath, missing))
    L = [START,
         "<!-- generated by speeduino-autobuild: tag=%s fmt=%d from %s/build-info.json; do not edit between the SPEEDUINO markers, it is overwritten -->"
         % (info["speeduino_tag"], FMT, d),
         "## Speeduino Firmware",
         "",
         "(Right click and 'Save link as...')"]
    for i, (f, label, color) in enumerate(BADGES):
        if i:
            L.append("")
        L += ["<!-- BEGIN LATEST DOWNLOAD BUTTON -->",
              BADGE % (label, color, label.replace("%20", " "), raw + f),
              "<!-- END LATEST DOWNLOAD BUTTON -->"]
    L.append(END)
    return nl.join(L) + nl, [raw + f for f, _, _ in BADGES]


def cmd_update(a, write=True):
    text = read(a.readme)
    nl = nl_of(text)
    info = json.load(open(os.path.join(a.dir, "build-info.json")))
    block, links = render(info, a.dir, a.branch, a.repo, a.server, a.release_tag, nl)
    lines = lines_of(text)
    sec = find_section(lines)
    if sec is not None:
        mode = "replaced the existing SPEEDUINO section (lines %d-%d)" % (sec[0] + 1, sec[1] + 1)
    else:
        sec = find_legacy(lines)
        if sec is not None:
            mode = "wrapped the existing Speeduino block (lines %d-%d) in SPEEDUINO markers" % (sec[0] + 1, sec[1] + 1)
    if sec is not None:
        tail_nl = lines[sec[1]].endswith(("\n", "\r"))
        if not tail_nl:
            block = block[: -len(nl)]
        new = "".join(lines[:sec[0]]) + block + "".join(lines[sec[1] + 1:])
    else:
        mode = "appended the SPEEDUINO section at the end"
        sep = "" if not text else (nl if text.endswith("\n") else nl + nl)
        new = text + sep + block
    if not write:
        sys.stdout.write(block)
        return 0
    for l in links:
        print("link: " + l)
    if new == text:
        print("readme: SPEEDUINO section already up to date")
        return 0
    check(text, new)
    with open(a.readme, "wb") as f:
        f.write(new.encode("utf-8"))
    print("readme: " + mode)
    return 0


def check(old, new):
    o, _ = strip_section(old, allow_legacy=True)
    n, nsec = strip_section(new, allow_legacy=False)
    if nsec is None:
        raise Fail("new readme has no SPEEDUINO section")
    if o != n:
        import difflib
        d = "".join(difflib.unified_diff(lines_of(o), lines_of(n), "old (SPEEDUINO section stripped)", "new (SPEEDUINO section stripped)"))
        raise Fail("readme changes outside the SPEEDUINO markers:\n" + d)


def cmd_check(a):
    check(read(a.old), read(a.new))
    print("readme: only the SPEEDUINO section differs")
    return 0


def cmd_current(a):
    text = sys.stdin.read() if a.readme == "-" else read(a.readme)
    lines = lines_of(text)
    sec = find_section(lines)
    if sec is None:
        print("no SPEEDUINO section")
        return 1
    m = STAMP_RE.search("".join(lines[sec[0]:sec[1] + 1]))
    if not m or m.group(1) != a.tag or int(m.group(2)) != FMT:
        print("SPEEDUINO section is outdated (%s)" % (str(m.groups()) if m else "no stamp"))
        return 1
    print("SPEEDUINO section is current (tag %s, fmt %d)" % (a.tag, FMT))
    return 0


def main():
    p = argparse.ArgumentParser()
    sp = p.add_subparsers(dest="cmd", required=True)
    for name in ("update", "render"):
        u = sp.add_parser(name)
        u.add_argument("readme")
        u.add_argument("--dir", required=True)
        u.add_argument("--branch", required=True)
        u.add_argument("--repo", required=True)
        u.add_argument("--server", default="https://github.com")
        u.add_argument("--release-tag", required=True)
    c = sp.add_parser("check"); c.add_argument("old"); c.add_argument("new")
    k = sp.add_parser("current"); k.add_argument("readme"); k.add_argument("--tag", required=True)
    a = p.parse_args()
    try:
        if a.cmd == "update":
            return cmd_update(a)
        if a.cmd == "render":
            return cmd_update(a, write=False)
        if a.cmd == "check":
            return cmd_check(a)
        return cmd_current(a)
    except Fail as e:
        print("::error::fw_readme: %s" % str(e).splitlines()[0], file=sys.stderr)
        print(str(e), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
